// lib/roadmap/plan.ts
// Pure roadmap domain helpers: AM/PM derivation, day grouping, progress.
// No database or network access here so every function is unit-testable.

export type RoutinePeriod = "am" | "pm" | "anytime";

export interface RoadmapTaskLike {
  id?: string;
  day: number;
  category: string;
  title: string;
  instructions: string;
  estimatedMinutes: number;
  isRestDay: boolean;
  needsProfessional: boolean;
  safetyNote?: string;
  completed?: boolean;
}

export interface RoadmapDay {
  day: number;
  tasks: RoadmapTaskLike[];
  am: RoadmapTaskLike[];
  pm: RoadmapTaskLike[];
  anytime: RoadmapTaskLike[];
  isRestDay: boolean;
  totalMinutes: number;
  completedCount: number;
}

/**
 * Derives the routine period from a task title/instructions.
 * Roadmaps generated by muse-spark-1.3 prefix titles with AM/PM; curated
 * tasks mention morning/evening rituals. Everything else is "anytime".
 */
export function deriveTaskPeriod(task: Pick<RoadmapTaskLike, "title" | "instructions">): RoutinePeriod {
  const text = `${task.title} ${task.instructions}`.toLowerCase();

  if (/^\s*(am|morning)\b/.test(text) || /\bmorning\b/.test(text.slice(0, 60))) {
    return "am";
  }
  if (/^\s*(pm|evening|night)\b/.test(text) || /\b(evening|before bed|night routine)\b/.test(text.slice(0, 60))) {
    return "pm";
  }
  return "anytime";
}

/** Groups a flat task list into ordered days with AM/PM splits. */
export function groupTasksByDay(tasks: RoadmapTaskLike[]): RoadmapDay[] {
  const byDay = new Map<number, RoadmapTaskLike[]>();

  for (const task of tasks) {
    const list = byDay.get(task.day) ?? [];
    list.push(task);
    byDay.set(task.day, list);
  }

  return [...byDay.entries()]
    .sort(([a], [b]) => a - b)
    .map(([day, dayTasks]) => {
      const am: RoadmapTaskLike[] = [];
      const pm: RoadmapTaskLike[] = [];
      const anytime: RoadmapTaskLike[] = [];

      for (const task of dayTasks) {
        const period = deriveTaskPeriod(task);
        if (period === "am") am.push(task);
        else if (period === "pm") pm.push(task);
        else anytime.push(task);
      }

      return {
        day,
        tasks: dayTasks,
        am,
        pm,
        anytime,
        isRestDay: dayTasks.length > 0 && dayTasks.every((t) => t.isRestDay),
        totalMinutes: dayTasks.reduce((sum, t) => sum + t.estimatedMinutes, 0),
        completedCount: dayTasks.filter((t) => t.completed).length,
      };
    });
}

/**
 * Mirror Scroll progress: completed tasks / total tasks as a 0–100 integer.
 * Rest days count like any other day — consistency, not intensity, is the goal.
 */
export function computeMirrorScrollProgress(tasks: RoadmapTaskLike[]): {
  percent: number;
  completed: number;
  total: number;
  currentDay: number;
  durationDays: number;
} {
  const total = tasks.length;
  const completed = tasks.filter((t) => t.completed).length;
  const percent = total === 0 ? 0 : Math.round((completed / total) * 100);

  const days = groupTasksByDay(tasks);
  const durationDays = days.length === 0 ? 30 : Math.max(...days.map((d) => d.day), 30);
  const currentDay =
    days.find((d) => d.completedCount < d.tasks.length)?.day ?? durationDays;

  return { percent, completed, total, currentDay, durationDays };
}

/** XP preview per task (display only; server-side XP lands in Phase 09). */
export function xpForTask(task: Pick<RoadmapTaskLike, "estimatedMinutes" | "isRestDay">): number {
  if (task.isRestDay) return 10;
  return Math.max(10, Math.min(40, Math.round(task.estimatedMinutes * 2)));
}
